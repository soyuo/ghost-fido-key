// Shared user-mode/kernel-mode control protocol for Ghost FIDO UDE.
#pragma once

#if !defined(_NTDDK_)
#include <winioctl.h>
#endif

#define GHOST_FIDO_UDE_PROTOCOL_MAJOR 1u
#define GHOST_FIDO_UDE_PROTOCOL_MINOR 2u
#define GHOST_FIDO_UDE_STATUS_SIGNATURE 0x44554647u /* "GFUD" on the wire */
#define GHOST_FIDO_UDE_MAX_STATUS_SIZE 256u

#define GHOST_FIDO_UDE_CAP_CONTROLLER_READY 0x00000001u
#define GHOST_FIDO_UDE_CAP_FIDO_HID_PROFILE 0x00000002u
#define GHOST_FIDO_UDE_CAP_ATTACH_DETACH 0x00000004u
#define GHOST_FIDO_UDE_CAP_REPORT_IO 0x00000008u
#define GHOST_FIDO_UDE_REQUIRED_CAPABILITIES \
    (GHOST_FIDO_UDE_CAP_CONTROLLER_READY | GHOST_FIDO_UDE_CAP_FIDO_HID_PROFILE | \
     GHOST_FIDO_UDE_CAP_ATTACH_DETACH | GHOST_FIDO_UDE_CAP_REPORT_IO)

#define IOCTL_GHOST_FIDO_UDE_QUERY_STATUS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x800, METHOD_BUFFERED, FILE_READ_ACCESS)
#define IOCTL_GHOST_FIDO_UDE_ATTACH \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define IOCTL_GHOST_FIDO_UDE_DETACH \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define IOCTL_GHOST_FIDO_UDE_WRITE_INPUT_REPORT \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x803, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define IOCTL_GHOST_FIDO_UDE_READ_OUTPUT_REPORT \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x804, METHOD_BUFFERED, FILE_READ_ACCESS)

#define GHOST_FIDO_UDE_REPORT_SIZE 64u
#define GHOST_FIDO_UDE_OPERATION_REQUEST_SIZE 16u
#define GHOST_FIDO_UDE_INPUT_REPORT_REQUEST_SIZE 84u
#define GHOST_FIDO_UDE_OUTPUT_REPORT_REQUEST_SIZE 16u
#define GHOST_FIDO_UDE_OUTPUT_REPORT_RESPONSE_SIZE 84u

typedef struct GHOST_FIDO_UDE_STATUS_REQUEST {
    ULONG Size;
    ULONG ProtocolMajor;
    ULONG ProtocolMinor;
    ULONG Reserved;
} GHOST_FIDO_UDE_STATUS_REQUEST;

typedef struct GHOST_FIDO_UDE_STATUS_RESPONSE {
    ULONG Size;
    ULONG Signature;
    ULONG ProtocolMajor;
    ULONG ProtocolMinor;
    ULONG Capabilities;
    ULONG InputReportSize;
    ULONG OutputReportSize;
    ULONG Reserved[2];
    ULONG VendorId;
    ULONG ProductId;
} GHOST_FIDO_UDE_STATUS_RESPONSE;

typedef struct GHOST_FIDO_UDE_OPERATION_REQUEST {
    ULONG Size;
    ULONG ProtocolMajor;
    ULONG ProtocolMinor;
    ULONG Reserved;
} GHOST_FIDO_UDE_OPERATION_REQUEST;

typedef struct GHOST_FIDO_UDE_INPUT_REPORT_REQUEST {
    ULONG Size;
    ULONG ProtocolMajor;
    ULONG ProtocolMinor;
    ULONG ReportSize;
    ULONG Reserved;
    UCHAR Report[GHOST_FIDO_UDE_REPORT_SIZE];
} GHOST_FIDO_UDE_INPUT_REPORT_REQUEST;

typedef struct GHOST_FIDO_UDE_OUTPUT_REPORT_REQUEST {
    ULONG Size;
    ULONG ProtocolMajor;
    ULONG ProtocolMinor;
    ULONG Reserved;
} GHOST_FIDO_UDE_OUTPUT_REPORT_REQUEST;

typedef struct GHOST_FIDO_UDE_OUTPUT_REPORT_RESPONSE {
    ULONG Size;
    ULONG ProtocolMajor;
    ULONG ProtocolMinor;
    ULONG ReportSize;
    ULONG Reserved;
    UCHAR Report[GHOST_FIDO_UDE_REPORT_SIZE];
} GHOST_FIDO_UDE_OUTPUT_REPORT_RESPONSE;

C_ASSERT(sizeof(GHOST_FIDO_UDE_STATUS_REQUEST) == 16);
C_ASSERT(sizeof(GHOST_FIDO_UDE_STATUS_RESPONSE) == 44);
C_ASSERT(sizeof(GHOST_FIDO_UDE_OPERATION_REQUEST) == GHOST_FIDO_UDE_OPERATION_REQUEST_SIZE);
C_ASSERT(sizeof(GHOST_FIDO_UDE_INPUT_REPORT_REQUEST) == GHOST_FIDO_UDE_INPUT_REPORT_REQUEST_SIZE);
C_ASSERT(sizeof(GHOST_FIDO_UDE_OUTPUT_REPORT_REQUEST) == GHOST_FIDO_UDE_OUTPUT_REPORT_REQUEST_SIZE);
C_ASSERT(sizeof(GHOST_FIDO_UDE_OUTPUT_REPORT_RESPONSE) == GHOST_FIDO_UDE_OUTPUT_REPORT_RESPONSE_SIZE);
